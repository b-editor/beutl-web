-- operation と sourceName は同じ migration (20260824040000) で入った。それより前に
-- 積まれた改名の予約には元の名前が無い。
--
-- 元の名前が無いと、後始末は「今の名前が元の名前だ」としか読めない。利用者が
-- 後から付け直した名前まで、古い改名の行き先へ書き換えてしまう。かといって
-- 動かさないことにすると、外す条件が永久に来ず、その名前を押さえ続ける。
--
-- 照合できない予約は残さない。押さえていた名前は空くが、これらの行が指す改名は
-- この upgrade で必ずプロセスごと終わっているので、後から着地することはない。
DELETE FROM "GitRepositoryCreation"
WHERE "operation" = 'RENAME' AND "sourceName" IS NULL;
